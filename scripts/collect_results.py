def fmt(d, lo, hi):
    if pd.isna(d):
        return ""
    star = "**" if (lo > 0 or hi < 0) else ""
    return f"{star}{d:+.3f} [{lo:+.3f}, {hi:+.3f}]{star}"


def headline_table(stem, settings):
    f, ft = f"{R}/{stem}.csv", f"{R}/{stem}_ref_xgbtuned.csv"
    if not os.path.exists(f):
        return f"_missing: {stem}.csv_\n"
    a = pd.read_csv(f)
    b = pd.read_csv(ft) if os.path.exists(ft) else None
    parts = []
    for s in settings:
        g = a[a.setting == s]
        if g.empty:
            continue
        rows = []
        for m in [m for m in ORDER if m in set(g.model)]:
            r = g[g.model == m].iloc[0]
            row = {"model": m, "AUC": f"{r.roc_auc:.4f}", "PR-AUC": f"{r.pr_auc:.4f}",
                   "ΔAUC vs xgboost [95% CI]": fmt(r.get("dAUC_vs_xgboost"), r.get("ci95_lo"), r.get("ci95_hi"))}
            if b is not None and not b[(b.setting == s) & (b.model == m)].empty:
                t = b[(b.setting == s) & (b.model == m)].iloc[0]
                row["ΔAUC vs xgboost_tuned [95% CI]"] = fmt(t.get("dAUC_vs_xgboost_tuned"), t.get("ci95_lo"), t.get("ci95_hi"))
            rows.append(row)
        parts.append(f"\n#### {s}\n\n" + pd.DataFrame(rows).to_markdown(index=False) + "\n")
    return "".join(parts)


def demote(md, levels=2):
    return re.sub(r"^(#+)", lambda m: "#" * (len(m.group(1)) + levels), md, flags=re.M)


def main():
    txt = ["# Results (auto-generated by scripts/collect_results.py)\n",
           "Pooled out-of-fold ROC-AUC on the committed folds. ΔAUC CIs: paired bootstrap over 25 km spatial blocks (Florida, Minnesota) "
           "or rows (Kentucky); **bold** = CI excludes 0. `*_tuned` = nested spatial CV, 100 Optuna trials (`baselines/tuned.py`). "
           "FMs in fp32. Headline settings were fixed in advance (`results/headline_family.md`): Florida no_landcover × ring × spatial5 and "
           "temporal, Kentucky loco, Minnesota sat_nolc × ring × spatial5.\n",
           ]
    txt.append("## 1. Headline grids\n")
    for title, stem, settings in HEADLINE:
        txt.append(f"\n### {title}\n" + headline_table(stem, settings))
    for i, (title, path) in enumerate(STUDIES, start=2):
        p = f"{R}/{path}"
        txt.append(f"\n## {i}. {title}\n")
        txt.append(demote(open(p).read()) if os.path.exists(p) else f"_not available yet: results/{path}_\n")
    with open(OUT, "w") as fh:
        fh.write("\n".join(txt))
    print(OUT, sum(len(t) for t in txt), "chars")


if __name__ == "__main__":
    main()
